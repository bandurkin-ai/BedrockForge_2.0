"""What the scenarios `blocks_*` share (ADR 0023 «Замеры», подшаг 17.39; ТЗ 8.7, 5.3, 7.31).

    ctx = Ctx.create(work)                     a project folder with an empty SQLite (the scenario's `prepare`)
    model = regular_model(ctx, rows, FIELDS)   a regular model of `rows` blocks written by portions of 2²⁰ rows
    model = sub_model(ctx, rows)               the model of `tools/gen/blockmodel.py` with sub-blocks (25 % of the
                                               parents split into eight), AU, DENSITY, F2…, DOM
    ctx = Ctx.open(work)                       the same project in the child process (`run`); `ctx.project` is what a
                                               route takes of `svc.require_current()`, `ctx.svc` the service of it
    limit_threads(params)                      `params["threads"]` cores (the CI runner has 2): numba, the pools and
                                               the affinity of the process

The scenarios run every operation as the job's body (`run_*` — what the handler of the job calls) or the route as a
function (the display) — the time of ТЗ is «от запроса до ответа при готовой модели». Data are generated by seeds:
the same numbers every run. What a scenario checks (a failure stops the run) is written in its docstring.
"""

from __future__ import annotations

import gc
import json
import os
import time
from collections.abc import Callable, Iterator, Mapping, Sequence
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import numpy as np

PORTION = 1 << 20  # rows of a row group and of a portion written
META = "blocks.json"
SIZE = (10.0, 10.0, 5.0)  # of a block of the regular models
CORNER = (500_000.0, 7_000_000.0, -200.0)
Fields = Sequence[Mapping[str, Any]]
Make = Callable[[np.random.Generator, int], dict[str, np.ndarray]]


def limit_threads(params: Mapping[str, Any]) -> int:
    """The process works on `params["threads"]` cores, as the runner of the profile does (ci — 2, full — 4): the
    threads of numba and of the pools of the core, and the affinity (the operating system gives it no more).
    Returns the number of threads."""
    want = int(params.get("threads") or (os.cpu_count() or 1))
    try:
        import numba

        numba.set_num_threads(max(1, min(want, int(numba.config.NUMBA_NUM_THREADS))))  # type: ignore[attr-defined]
    except ImportError:  # no numba: nothing to limit
        pass
    cores = os.cpu_count() or 1
    if hasattr(os, "sched_setaffinity") and want < cores:
        try:
            os.sched_setaffinity(0, sorted(os.sched_getaffinity(0))[:want])
        except OSError:
            pass
    os.cpu_count = lambda: want  # type: ignore[assignment]  # `strips.default_threads` of the jobs reads it
    return want


def peak_mb() -> float | None:
    from bench.run import peak_rss_mb

    got = peak_rss_mb()
    return None if got is None else round(got, 1)


class Ctx:
    """A project folder of a scenario: the engine, the store, the model ids of `blocks.json`."""

    def __init__(self, work: Path, engine: Any) -> None:
        from bf_core.storage.blobs import BlobStore

        self.work, self.engine, self.folder = work, engine, work
        self.store = BlobStore(work)
        self.project = SimpleNamespace(engine=engine, folder=work, uid=f"bench:{work}")
        self.svc = SimpleNamespace(require_current=lambda writable=False: self.project)

    @classmethod
    def create(cls, work: Path) -> Ctx:
        from bf_core.db import dialect, migrate

        engine = dialect.create_engine(dialect.sqlite_url(str(work / "project.sqlite")))
        migrate.upgrade(engine, "project")
        ctx = cls(work, engine)
        ctx.store.tmp_dir.mkdir(parents=True, exist_ok=True)
        return ctx

    @classmethod
    def open(cls, work: Path) -> Ctx:
        from bf_core.db import dialect

        ctx = cls(work, dialect.create_engine(dialect.sqlite_url(str(work / "project.sqlite"))))
        ctx.store.tmp_dir.mkdir(parents=True, exist_ok=True)
        return ctx

    def close(self) -> None:
        self.engine.dispose()

    def keep(self, **meta: Any) -> None:
        """The facts of the model `prepare` made (`meta()` of the child)."""
        (self.work / META).write_text(json.dumps(meta, ensure_ascii=False), encoding="utf-8")

    def meta(self) -> dict[str, Any]:
        return dict(json.loads((self.work / META).read_text(encoding="utf-8")))

    def model(self, model_id: int) -> Any:
        from bf_core.blocks.model import Model
        from bf_core.db import dialect

        with dialect.read_tx(self.engine) as conn:
            return Model.open(conn, self.store, model_id)

    def version(self, model_id: int) -> int:
        return int(self.model(model_id).version)


def commit(ctx: Ctx, staged: Any, name: str, source: Mapping[str, Any] | None = None) -> int:
    from bf_core.blocks import store as bm
    from bf_core.db import dialect

    try:
        with dialect.write_tx(ctx.engine) as conn:
            return int(bm.commit_block_model(conn, ctx.store, staged, name=name, source=source))
    finally:
        staged.discard()


def regular_model(
    ctx: Ctx, rows: int, fields: Fields, make: Make, *, name: str = "Модель замера", seed: int = 1, nz: int = 200,
    size: Sequence[float] = SIZE, rotation: float = 0.0,
) -> dict[str, Any]:  # fmt: skip
    """A regular model of `rows` parents (no sub-blocks; a grid of nz layers, the rest of it square), the values
    of `make(rng, n)` for every portion. → {model_id, rows, counts}."""
    from bf_core.blocks import store as bm

    nxy = int(np.ceil(np.sqrt(rows / nz)))
    grid = {"corner": list(CORNER), "counts": [nxy, nxy, nz], "size": list(size), "rotation": rotation}
    rng = np.random.default_rng(seed)
    with bm.CellsWriterV2(ctx.store, grid, fields, row_group=PORTION) as w:
        for lo in range(0, rows, PORTION):
            n = min(PORTION, rows - lo)
            w.write(np.arange(lo, lo + n, dtype=np.uint64), make(rng, n))
        staged = w.finish()
    gc.collect()
    return {"model_id": commit(ctx, staged, name), "rows": rows, "counts": [nxy, nxy, nz]}


def grade_fields() -> list[dict[str, Any]]:
    """The fields of the regular model of the calculator, the filter, the report and the export."""
    return [
        {"name": "AU", "dtype": "f8", "unit": "g/t"},
        {"name": "CU", "dtype": "f4", "unit": "%"},
        {"name": "DENS", "dtype": "f8", "unit": "т/м³"},
        {"name": "DOM", "dtype": "cat", "labels": ["A", "B", "C", "D"]},
        {"name": "DOMAIN", "dtype": "f8"},
    ]


def grade_values(rng: np.random.Generator, n: int) -> dict[str, np.ndarray]:
    au = rng.lognormal(0.0, 1.0, n)
    au[rng.random(n) < 0.03] = np.nan  # 3 % have no value: NaN is not a number
    domain = rng.integers(0, 5, n).astype(np.float64)
    domain[rng.random(n) < 0.02] = np.nan
    return {"AU": au, "CU": rng.random(n).astype(np.float32), "DENS": rng.normal(2.7, 0.1, n),
            "DOM": rng.integers(-1, 4, n).astype(np.int32), "DOMAIN": domain}  # fmt: skip


def wide_fields(count: int) -> list[dict[str, Any]]:
    """`count` number fields (the export and the import of ТЗ: 20 fields): AU, DENSITY, F2 …"""
    return [{"name": n, "dtype": "f8"} for n in ("AU", "DENSITY", *[f"F{i}" for i in range(2, count)])]


def wide_values(count: int) -> Make:
    names = [f["name"] for f in wide_fields(count)]

    def make(rng: np.random.Generator, n: int) -> dict[str, np.ndarray]:
        return {k: (rng.lognormal(0.0, 1.0, n) if k == "AU" else rng.normal(2.7, 0.05, n) if k == "DENSITY"
                    else rng.random(n)) for k in names}  # fmt: skip

    return make


def sub_model(
    ctx: Ctx, rows: int, *, fields: int = 4, rotation: float = 0.0, name: str = "Модель с субблоками", seed: int = 1,
    div: tuple[int, int, int] = (4, 4, 2), share: float = 0.25,
) -> dict[str, Any]:  # fmt: skip
    """The model of `tools/gen/blockmodel.py::sub_chunks`: `rows` rows, `share` of the parents split into eight
    octants, a grid of div (4, 4, 2); fields AU, DENSITY, F2 …, the smooth field SM (`blockmodel.smooth`: a filter
    at 0.78 takes bodies, not noise) and the category DOM (a, b, c). The rows are in the order of the file.
    → {model_id, rows, parents, counts}."""
    from tools.gen.blockmodel import smooth, sub_chunks
    from tools.gen.blockmodel import sub_model as grid_of

    from bf_core.blocks import store as bm

    grid = {**grid_of(rows, div, share), "rotation": float(rotation)}
    spec = [*wide_fields(fields), {"name": "SM", "dtype": "f8"},
            {"name": "DOM", "dtype": "cat", "labels": ["a", "b", "c"]}]  # fmt: skip
    rng = np.random.default_rng(seed + 1000)
    with bm.CellsWriterV2(ctx.store, grid, spec, row_group=PORTION) as w:
        for p, s, ww, values in sub_chunks(rows, div, share, 1 << 18, seed, fields):
            values["SM"] = smooth(p, grid["counts"], seed)
            values["DOM"] = rng.integers(0, 3, len(p)).astype(np.int32)
            w.write(p, values, s, ww)
        staged = w.finish()
        parents, written = w.parents, w.rows
    gc.collect()
    return {"model_id": commit(ctx, staged, name), "rows": written, "parents": parents, "counts": grid["counts"]}


def portions(model: Any, names: Sequence[str], size: int = PORTION) -> Iterator[Any]:
    yield from model.iter(list(names), size)


