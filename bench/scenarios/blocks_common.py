class Clock:
    """Seconds of named stages: `with clock("read"): …` → `info["read_s"]`."""

    def __init__(self, info: dict[str, Any], prefix: str = "") -> None:
        self.info, self.prefix = info, prefix

    def __call__(self, key: str) -> Clock._Stage:
        return Clock._Stage(self, key)

    class _Stage:
        def __init__(self, clock: Clock, key: str) -> None:
            self.clock, self.key = clock, key

        def __enter__(self) -> None:
            self.t0 = time.perf_counter()

        def __exit__(self, *_: Any) -> None:
            self.clock.info[f"{self.clock.prefix}{self.key}_s"] = round(time.perf_counter() - self.t0, 3)


def median(values: Sequence[float]) -> float:
    return float(np.median(np.asarray(values, dtype=np.float64)))
