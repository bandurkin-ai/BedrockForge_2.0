"""Demo parts of Э7 (ТЗ 7.5, 7.18–7.20, 7.35 Д-16): what lies around the holes of «Скважины 2025».

  trench   the trench «К-01» in the set of holes — a polyline dug across the ore zone: a collar, a survey
           station with coordinates at every vertex and 2 m samples along it (`importing/trenches.py`);
  lines    the file «Рудное тело и дорога»: closed strings of the ore lens on the six section lines of the
           grid and the road south of the site (`lines/store.py`);
  terrain  the file «Топосъёмка» with the survey points, the plan «План участка» — a picture drawn here
           with its world file, read as any image is (`formats/raster_image.py`) — and the DTM «Рельеф» built
           from the points, the collars and the road (`geo/dtm.py`), with the plan laid on it.

Everything is generated by code from the random stream of the demo (after the holes, so they stay as they were)
and from the holes themselves: the relief passes through their collars, the ore strings follow the lens the
grades were made from. Coordinates are float64; an unknown height would be NaN, never 0 (there is none here).
"""

from __future__ import annotations

import io
import json
import math
import random
import tempfile
from pathlib import Path
from typing import Any

import numpy as np
import sqlalchemy as sa

from bf_core.db import dialect
from bf_core.db.schema import dh_holes, dh_rows, dh_tables, objects
from bf_core.storage.blobs import BlobStore

from .drillholes import SET_NAME

AREA = (4900.0, 7900.0, 5450.0, 8350.0)  # x0, y0, x1, y1 of the survey and of the plan
PAD = (4994.0, 7994.0, 5356.0, 8256.0)  # the hole grid (8 × 6 holes at 50 m, each within 5 m of its node)
PIXEL = 0.5  # metres in a pixel of the plan
TRENCH = "К-01"
LINES_FILE, SURVEY_FILE, PLAN, DTM = "Рудное тело и дорога", "Топосъёмка", "План участка", "Рельеф"
ORE, ROAD, POINTS = "Рудное тело", "Дорога", "Пикеты"
ORE_COLOR, ROAD_COLOR, POINTS_COLOR = "#e05d6f", "#9a8f7a", "#5fbf6a"
LEVEL = 420.0  # the collars of the demo are at 420 ± 6 m


def _set_id(conn: sa.Connection) -> int:
    same = sa.and_(objects.c.kind == "drillhole_set", objects.c.name_key == dialect.name_key(SET_NAME))
    return int(conn.execute(sa.select(objects.c.id).where(same)).scalar_one())


def _collars(conn: sa.Connection) -> np.ndarray:
    """Collars of the drilled holes of the demo set, (n, 3): the trench is not one of them."""
    h = dh_holes.c
    rows = conn.execute(
        sa.select(h.x, h.y, h.z).where(h.set_id == _set_id(conn), h.name.like("DH-%")).order_by(h.id)
    ).all()
    return np.array(rows, dtype=np.float64).reshape(-1, 3)


def relief(x: Any, y: Any, collars: np.ndarray) -> np.ndarray:
    """The height of the ground: a plateau at the hole grid that the collars pull to their heights (inverse
    squared distance, softened by 0.2 m, fading over about 40 m) and hills around it."""
    x, y = np.asarray(x, dtype=np.float64), np.asarray(y, dtype=np.float64)
    outside = np.hypot(
        np.maximum(np.maximum(PAD[0] - x, x - PAD[2]), 0.0), np.maximum(np.maximum(PAD[1] - y, y - PAD[3]), 0.0)
    )
    s = np.clip(outside / 120.0, 0.0, 1.0)
    hills = 9.0 * np.sin((x - AREA[0]) / 95.0) * np.cos((y - AREA[1]) / 80.0) + 0.03 * (x - 5175.0)
    w = 1.0 / ((x[..., None] - collars[:, 0]) ** 2 + (y[..., None] - collars[:, 1]) ** 2 + 0.04)
    pull = (w * (collars[:, 2] - LEVEL)).sum(axis=-1) / (w.sum(axis=-1) + 1.0 / 40.0**2)
    return np.asarray(LEVEL + s * s * (3.0 - 2.0 * s) * hills + pull)


def _on_ground(xy: np.ndarray, collars: np.ndarray, below: float = 0.0) -> np.ndarray:
    """(n, 2) plan points as (n, 3) on the relief, heights in centimetres as a survey gives them."""
    return np.column_stack([xy, np.round(relief(xy[:, 0], xy[:, 1], collars) - below, 2)])


def trench_line(collars: np.ndarray) -> np.ndarray:
    """The axis of the trench: across the ore zone between two rows of holes, a metre and a half deep."""
    x = np.linspace(5062.0, 5302.0, 9)
    y = 8126.0 + 7.0 * np.sin((x - 5062.0) / 60.0)
    return _on_ground(np.round(np.column_stack([x, y]), 2), collars, below=1.5)


def road_lines(collars: np.ndarray) -> list[np.ndarray]:
    """The road south of the site and the spur to the drill pads, on the ground."""
    x = np.linspace(AREA[0] + 6.0, AREA[2] - 6.0, 19)
    main = np.column_stack([x, 7952.0 + 22.0 * np.sin((x - AREA[0]) / 90.0)])
    turn = main[9]
    spur = np.array([turn, [turn[0] + 4.0, 7975.0], [turn[0] - 2.0, 7996.0]])
    return [_on_ground(np.round(main, 2), collars), _on_ground(np.round(spur, 2), collars)]


def ore_strings(rng: random.Random) -> tuple[list[np.ndarray], list[float]]:
    """A closed string of the ore lens on every section line Y = 8000 … 8250: the lens the grades of the
    samples were made from (its centre at 90 + 6·column m along a hole that dips 60° to the east)."""
    along = np.array([0.5, -math.sin(math.radians(60.0))])  # (x, z) of a metre down the hole
    lines, sections = [], []
    for row in range(6):
        y = 8000.0 + row * 50.0
        upper, lower = [], []
        for col in range(8):
            centre = np.array([5045.0 + 53.0 * col, 342.0 - 5.2 * col])
            half = 20.0 * (1.0 - 0.3 * ((col - 3.5) / 4.0) ** 2) + rng.uniform(-2.0, 2.0)
            upper.append(centre - half * along)
            lower.append(centre + half * along)
        tips = (np.array([5045.0 - 32.0, 342.0 + 3.1]), np.array([5045.0 + 53.0 * 7.6, 342.0 - 5.2 * 7.6]))
        ring = np.array([tips[0], *upper, tips[1], *lower[::-1]])
        lines.append(np.round(np.column_stack([ring[:, 0], np.full(len(ring), y), ring[:, 1]]), 2))
        sections.append(y)
    return lines, sections


# --- the trench ------------------------------------------------------------------------------------------


def add_trench(conn: sa.Connection, _store: BlobStore, rng: random.Random) -> None:
    from bf_core.drillholes.store import pack
    from bf_core.importing.trench_lines import Trenches
    from bf_core.importing.trenches import write_trenches

    set_id = _set_id(conn)
    xyz = trench_line(_collars(conn))
    steps = np.linalg.norm(np.diff(xyz, axis=0), axis=1)
    depth = np.concatenate([[0.0], np.cumsum(steps)])  # the depth of a vertex is the 3D length to it
    offsets = np.array([0, len(xyz)], dtype=np.int64)
    write_trenches(conn, set_id, Trenches([TRENCH], offsets, xyz, depth), lambda _f, _m: None)
    hole = int(
        conn.execute(sa.select(dh_holes.c.id).where(dh_holes.c.set_id == set_id, dh_holes.c.name == TRENCH)).scalar_one()
    )
    table = conn.execute(
        sa.select(dh_tables.c.id, dh_tables.c.row_count).where(dh_tables.c.set_id == set_id, dh_tables.c.kind == "assay")
    ).one()
    length = float(depth[-1])
    rows: list[tuple[object, ...]] = []
    start = 0.0
    while start < length - 1e-9:
        stop = min(start + 2.0, length)
        ore = math.exp(-(((start + stop) / 2.0 - length * 0.55) ** 2) / (2.0 * 28.0**2))
        au = round(max(0.005, rng.lognormvariate(-2.4, 0.8) + 2.5 * ore * rng.random()), 3)
        cu = round(max(0.01, rng.gauss(0.18, 0.06) + 0.4 * ore), 3)
        sample = json.dumps({"0": f"{TRENCH}-{len(rows):03d}"}, ensure_ascii=False)
        rows.append((int(table.id), hole, start, stop, pack([au, cu]), sample))
        start = stop
    dialect.bulk_insert(conn, dh_rows, ("table_id", "hole_id", "from_m", "to_m", "num", "txt"), rows)
    conn.execute(
        sa.update(dh_tables).where(dh_tables.c.id == int(table.id)).values(row_count=int(table.row_count) + len(rows))
    )


# --- lines -----------------------------------------------------------------------------------------------


def _line_file(conn: sa.Connection, store: BlobStore, name: str) -> int:
    from bf_core.lines import store as ls

    meta = {"format": "demo", "label": "демо-данные", "filename": None, "fields": [], "warnings": []}
    return ls.create_file(conn, store, name=name, meta=meta)


def add_lines(conn: sa.Connection, store: BlobStore, rng: random.Random) -> None:
    from bf_core.formats.lineset import from_lines
    from bf_core.lines import store as ls

    strings, sections = ore_strings(rng)
    ore = from_lines(
        ORE,
        strings,
        closed=[True] * len(strings),
        attrs={"Разрез": [f"Y {y:.0f}" for y in sections], "Y": sections},
        color=ORE_COLOR,
        units={"Y": "м"},
    )
    road = from_lines(
        ROAD, road_lines(_collars(conn)), closed=[False, False], attrs={"Название": ["Дорога", "Подъезд к буровым"]},
        color=ROAD_COLOR,
    )  # fmt: skip
    file_id = _line_file(conn, store, LINES_FILE)
    for k, layer in enumerate((ore, road)):
        ls.put_layer(conn, store, layer, file_id=file_id, sort_key=float(k))


# --- the survey, the plan and the DTM --------------------------------------------------------------------


def survey_points(collars: np.ndarray, rng: random.Random) -> tuple[np.ndarray, list[str]]:
    """Survey points: a 25 m grid walked with a few metres of freedom, the road and the axis of the trench."""
    xy, codes = [], []
    for gy in np.arange(AREA[1], AREA[3] + 1.0, 25.0):
        for gx in np.arange(AREA[0], AREA[2] + 1.0, 25.0):
            x = min(max(gx + rng.uniform(-8.0, 8.0), AREA[0]), AREA[2])
            y = min(max(gy + rng.uniform(-8.0, 8.0), AREA[1]), AREA[3])
            xy.append((round(x, 2), round(y, 2)))
            codes.append("рельеф")
    ground = _on_ground(np.array(xy), collars)
    trench = trench_line(collars)
    edge = np.column_stack([trench[:, :2], np.round(trench[:, 2] + 1.5, 2)])  # its edge is the ground itself
    return np.vstack([ground, edge]), [*codes, *["канава"] * len(edge)]


def plan_png(collars: np.ndarray, strings: list[np.ndarray]) -> tuple[bytes, int, int]:
    """The plan of the site as a picture: rock units, contours of the relief every 2 m, the 50 m grid, the
    outline of the ore lens, the road, the trench and the collars. Returns (PNG, width, height)."""
    from PIL import Image, ImageDraw

    width, height = round((AREA[2] - AREA[0]) / PIXEL), round((AREA[3] - AREA[1]) / PIXEL)
    step = 4  # the relief is computed every 2 m and stretched to the pixels: smooth enough for contours
    cx = AREA[0] + (np.arange(0, width, step) + step / 2) * PIXEL
    cy = AREA[3] - (np.arange(0, height, step) + step / 2) * PIXEL
    coarse = relief(*np.meshgrid(cx, cy), collars).astype(np.float32)
    z = np.asarray(Image.fromarray(coarse).resize((width, height), Image.Resampling.BILINEAR), dtype=np.float64)
    x, y = np.meshgrid(AREA[0] + (np.arange(width) + 0.5) * PIXEL, AREA[3] - (np.arange(height) + 0.5) * PIXEL)
    unit = np.floor(((x - AREA[0]) * 0.6 + (y - AREA[1]) * 0.35 + 25.0 * np.sin((y - AREA[1]) / 70.0)) / 110.0)
    palette = np.array(
        [[232, 224, 201], [214, 226, 205], [226, 212, 196], [205, 219, 226], [233, 226, 187], [219, 208, 220]],
        dtype=np.uint8,
    )
    pixels = palette[unit.astype(np.int64) % len(palette)]
    level = np.floor(z / 2.0)
    contour = np.zeros(level.shape, dtype=bool)
    contour[:, :-1] |= level[:, :-1] != level[:, 1:]
    contour[:-1, :] |= level[:-1, :] != level[1:, :]
    pixels[contour] = (150, 118, 84)
    image = Image.fromarray(pixels)
    draw = ImageDraw.Draw(image, "RGBA")

    def px(points: np.ndarray) -> list[tuple[float, float]]:
        return [((p[0] - AREA[0]) / PIXEL, (AREA[3] - p[1]) / PIXEL) for p in points.tolist()]

    for gxl in np.arange(AREA[0], AREA[2] + 1.0, 50.0):
        draw.line(px(np.array([[gxl, AREA[1]], [gxl, AREA[3]]])), fill=(90, 100, 110, 110), width=1)
    for gyl in np.arange(AREA[1], AREA[3] + 1.0, 50.0):
        draw.line(px(np.array([[AREA[0], gyl], [AREA[2], gyl]])), fill=(90, 100, 110, 110), width=1)
    lens = np.vstack(strings)
    x0, x1 = float(lens[:, 0].min()), float(lens[:, 0].max())
    outline = np.array([[x0, 7985.0], [x1, 7985.0], [x1, 8265.0], [x0, 8265.0]])
    draw.polygon(px(outline), fill=(224, 93, 111, 60), outline=(190, 60, 80, 255))
    for line in road_lines(collars):
        draw.line(px(line), fill=(122, 98, 70, 255), width=5)
    draw.line(px(trench_line(collars)), fill=(200, 40, 40, 255), width=4)
    for cx, cy in px(collars):
        draw.ellipse([cx - 4, cy - 4, cx + 4, cy + 4], fill=(30, 36, 44, 255), outline=(255, 255, 255, 255))
    draw.rectangle([0, 0, width - 1, height - 1], outline=(60, 70, 80, 255), width=3)
    out = io.BytesIO()
    image.save(out, format="PNG", optimize=False, compress_level=6)
    return out.getvalue(), width, height


def _add_plan(conn: sa.Connection, store: BlobStore, collars: np.ndarray, strings: list[np.ndarray]) -> int:
    """The plan goes the way of an imported image: a PNG with its world file is read, its display copies made."""
    from bf_core.formats.raster_image import read_raster
    from bf_core.importing.object_files import _raster_summary
    from bf_core.rasters import store as rs

    png, _width, _height = plan_png(collars, strings)
    # the world file: the centre of the top-left pixel (ТЗ 7.19)
    world = (PIXEL, 0.0, 0.0, -PIXEL, AREA[0] + PIXEL / 2, AREA[3] - PIXEL / 2)
    with tempfile.TemporaryDirectory(prefix="bf-demo-", ignore_cleanup_errors=True) as tmp:
        image = Path(tmp) / f"{PLAN}.png"
        image.write_bytes(png)
        sidecar = image.with_suffix(".pgw")
        sidecar.write_text("".join(f"{v!r}\n" for v in world), encoding="ascii")
        r = read_raster(image)
        summary, georef, _notes = _raster_summary(r, None, 0.0)
        meta = {
            "format": r.info.format, "filename": image.name, "size": len(png), "mode": r.info.mode,
            "bits": r.info.bits, "sidecars": summary["sidecars"], "warnings": list(r.warnings),
        }  # fmt: skip
        displays = rs.stage_displays(store, r.displays)
        try:
            raster_id = rs.create_raster(
                conn, store, name=PLAN, width=r.width, height=r.height, georef=georef, checks=r.checks,
                displays=displays, meta=meta,
            )  # fmt: skip
        finally:
            displays.discard()
        rs.attach(conn, store, raster_id, "source", store.stage_file(image), "image/png")
        rs.attach(conn, store, raster_id, "sidecar:pgw", store.stage_file(sidecar), "text/plain")
    return raster_id


def add_terrain(conn: sa.Connection, store: BlobStore, rng: random.Random) -> None:
    from bf_core.formats.lineset import from_points
    from bf_core.geo.dtm import build_dtm
    from bf_core.lines import store as ls
    from bf_core.wireframes import store as wf

    collars = _collars(conn)
    xyz, codes = survey_points(collars, rng)
    points = from_points(
        POINTS, xyz, attrs={"N": [float(i + 1) for i in range(len(xyz))], "Код": codes}, color=POINTS_COLOR
    )
    file_id = _line_file(conn, store, SURVEY_FILE)
    points_id = ls.put_layer(conn, store, points, file_id=file_id)

    lines_file = conn.execute(
        sa.select(objects.c.id).where(objects.c.kind == ls.LINE_FILE, objects.c.name == LINES_FILE)
    ).scalar_one()
    road_id = ls.layer_ids(conn, int(lines_file))[1]
    road = ls.read_layer(conn, store, road_id)
    ore = ls.read_layer(conn, store, ls.layer_ids(conn, int(lines_file))[0])
    raster_id = _add_plan(conn, store, collars, [ore.line(i) for i in range(ore.line_count)])

    # «Построить ЦТМ» from the survey points, the collars of the holes and the road as structural lines
    breaklines = [np.asarray(road.line(i), dtype=np.float64) for i in range(road.line_count)]
    v, t, report = build_dtm(np.vstack([xyz, collars]), breaklines)
    built = {
        "kind": "dtm",
        "method": report["method"],
        "sources": [
            {"kind": "line_layer", "id": points_id, "name": POINTS, "points": len(xyz)},
            {"kind": "line_layer", "id": road_id, "name": ROAD, "points": road.point_count,
             "segments": road.point_count - road.line_count},
            {"kind": "drillhole_set", "id": _set_id(conn), "name": SET_NAME, "collars": len(collars)},
        ],
        "params": {"breaklines": True, "boundary": None, "max_edge": None},
        "report": {k: report[k] for k in report if k != "method"},
    }  # fmt: skip
    wf.put_wireframe(conn, store, v, t, name=DTM, dtm=True, raster_id=raster_id, meta={"built": built})
